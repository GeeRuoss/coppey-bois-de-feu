const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('dist/analytics.js', 'utf8');
function browser(choice) {
  const values = new Map();
  if (choice) values.set('coppey-analytics-consent-v1', JSON.stringify({choice, at: Date.now()}));
  const buttons = Object.fromEntries(['accept', 'reject'].map(choice => [choice, {dataset:{analyticsChoice:choice}, addEventListener(type, fn){this.click=fn;}}]));
  const settings = {hidden:true, addEventListener(type, fn){this.click=fn;}, focus(){}};
  const panel = {hidden:true, querySelectorAll(){return Object.values(buttons);}, querySelector(){return {focus(){}};}};
  const loaded = [], listeners = {};
  const location = {hostname:'coppeyboisdefeu.ch', origin:'https://coppeyboisdefeu.ch', pathname:'/reservation/', search:'?adresse=information-privee', reload(){this.reloaded=true;}};
  const document = {currentScript:{dataset:{measurementId:'G-TEST123'}}, title:'Coppey', referrer:'https://example.com/?secret=prive', cookie:'', getElementById(id){return id==='analytics-choice'?panel:settings;},createElement(){return {};},head:{append(script){loaded.push(script);}},addEventListener(type,fn){listeners[type]=fn;}};
  const context={document,location,URL,Date,localStorage:{getItem:key=>values.get(key)||null,setItem:(key,value)=>values.set(key,value)}};
  context.window=context;
  vm.runInNewContext(source,context);
  return {context,buttons,settings,panel,loaded,listeners,values};
}
const first=browser();
assert.equal(first.loaded.length,0,'Aucune requête Google avant accord');
assert.equal(first.context.dataLayer,undefined);
assert.equal(first.panel.hidden,false);
first.buttons.reject.click();
assert.equal(first.loaded.length,0,'Refus sans requête Google');
assert.equal(first.panel.hidden,true);
assert.equal(browser('reject').loaded.length,0,'Refus conservé au rechargement');
const accepted=browser(); accepted.buttons.accept.click();
assert.equal(accepted.loaded.length,1);
assert(accepted.loaded[0].src.endsWith('id=G-TEST123'));
const config=accepted.context.dataLayer.find(args=>args[0]==='config')[2];
assert.equal(config.page_location,'https://coppeyboisdefeu.ch/reservation/');
assert.equal(config.page_referrer,'https://example.com/');
assert.equal(config.allow_google_signals,false);
accepted.listeners.click({target:{closest:()=>({href:'https://wa.me/41792903493?text=message-prive'})}});
const contact=accepted.context.dataLayer.at(-1);
assert.equal(contact[1],'contact_whatsapp');
assert(!JSON.stringify(contact).includes('message-prive'));
accepted.buttons.reject.click();
assert.equal(accepted.context['ga-disable-G-TEST123'],true);
assert.equal(accepted.context.location.reloaded,true,'Retrait recharge la page sans balise');
assert.equal(browser('accept').loaded.length,1,'Accord conservé au rechargement');
console.log('Analytics : attente, refus, accord, rechargement, retrait et données minimales vérifiés.');
